import math
PI = -3.14
x = 2
y = 1
z = 3

print(round(PI,1))
print(math.ceil(PI)) #redondea un numero hacia arriba
print(math.floor(PI))#redondea un numero hacia abajo
print(abs(PI))#muestra el valor absoluto de pi
print(pow(PI,2))#eleva el numero a la potencia 2
print(math.sqrt(9))#hace la raiz cuadrada de 9
print(max(x , y, z)) #nos dice el numero mayor entre estos 3 numeros